-- Etapa 8: recibos de sueldo y costos de la IA.

ALTER TABLE uso_ia DROP CONSTRAINT ck_uso_ia_proposito;
ALTER TABLE uso_ia ADD CONSTRAINT ck_uso_ia_proposito
    CHECK (proposito IN ('TEXTO', 'AUDIO', 'TICKET', 'RECIBO', 'RESUMEN', 'CONSULTA'));

ALTER TABLE movimiento DROP CONSTRAINT ck_movimiento_origen;
ALTER TABLE movimiento ADD CONSTRAINT ck_movimiento_origen
    CHECK (origen IN ('TEXTO', 'AUDIO', 'TICKET', 'AVISO', 'RESUMEN', 'DASHBOARD', 'AUTOMATICO', 'RECIBO'));

-- Un recibo de sueldo leído: el ingreso (por el neto) es su movimiento. A propósito no hay columnas para el CUIL,
-- el CBU, el legajo ni el domicilio.
CREATE TABLE recibo_sueldo (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    movimiento_id BIGINT         NOT NULL UNIQUE REFERENCES movimiento (id),
    empleador     VARCHAR(100)   NOT NULL,
    -- Siempre el día 1 del mes que liquida el recibo.
    periodo       DATE           NOT NULL,
    fecha_pago    DATE,
    tipo          VARCHAR(20)    NOT NULL,
    bruto         NUMERIC(14, 2) NOT NULL,
    descuentos    NUMERIC(14, 2) NOT NULL,
    neto          NUMERIC(14, 2) NOT NULL,
    -- Relativa a la carpeta de datos: recibos/AAAA/MM/<id>.pdf o .jpg
    archivo       VARCHAR(255),
    -- Lo que no cerró al leerlo, para mostrarlo en la tarjeta (vacío si cerró todo).
    aviso         VARCHAR(500),
    CONSTRAINT ck_recibo_tipo CHECK (tipo IN ('SUELDO_MENSUAL', 'AGUINALDO', 'VACACIONES', 'LIQUIDACION_FINAL'))
);

CREATE INDEX ix_recibo_periodo ON recibo_sueldo (periodo);

CREATE TABLE recibo_concepto (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recibo_id   BIGINT         NOT NULL REFERENCES recibo_sueldo (id) ON DELETE CASCADE,
    descripcion VARCHAR(150)   NOT NULL,
    grupo       VARCHAR(20)    NOT NULL,
    importe     NUMERIC(14, 2) NOT NULL,
    orden       INT            NOT NULL,
    CONSTRAINT ck_recibo_concepto_grupo CHECK (grupo IN ('REMUNERATIVO', 'NO_REMUNERATIVO', 'DESCUENTO'))
);

CREATE INDEX ix_recibo_concepto_recibo ON recibo_concepto (recibo_id, orden);

-- Avisos del tope mensual de gasto en IA: uno por mes y por umbral (80 y 100 por ciento), para no repetirlos.
CREATE TABLE aviso_tope_ia (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mes       DATE      NOT NULL,
    umbral    INT       NOT NULL,
    enviado_en TIMESTAMP NOT NULL,
    CONSTRAINT uq_aviso_tope_ia UNIQUE (mes, umbral)
);

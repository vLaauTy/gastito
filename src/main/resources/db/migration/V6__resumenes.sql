-- Etapa 4: resúmenes semanales y mensuales. Tiene que correr igual en H2 y en PostgreSQL.

-- Cada resumen que se armó, automático o pedido con /resumen. Los números los calcula Java (datos, en JSON) y
-- la IA solo redacta las observaciones y el consejo a partir de ellos.
CREATE TABLE resumen (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo                 VARCHAR(20)     NOT NULL,
    -- El período, con los dos días incluidos (lunes a domingo, o el mes).
    desde                DATE            NOT NULL,
    hasta                DATE            NOT NULL,
    -- Pedido antes de que termine el período: los datos llegan hasta "hasta", que es anterior al fin.
    parcial              BOOLEAN         NOT NULL DEFAULT FALSE,
    automatico           BOOLEAN         NOT NULL,
    datos                VARCHAR(100000) NOT NULL,
    -- Una observación por renglón. Vacías si la IA no estuvo o si su texto no pasó el control de números.
    observaciones        VARCHAR(4000),
    consejo              VARCHAR(1000),
    -- La IA escribió un número que no está en los datos: se mandó solo la parte numérica.
    texto_ia_descartado  BOOLEAN         NOT NULL DEFAULT FALSE,
    uso_ia_id            BIGINT REFERENCES uso_ia (id),
    creado_en            TIMESTAMP       NOT NULL,
    enviado_en           TIMESTAMP,
    CONSTRAINT ck_resumen_tipo CHECK (tipo IN ('SEMANAL', 'MENSUAL')),
    CONSTRAINT ck_resumen_periodo CHECK (desde <= hasta)
);

CREATE INDEX ix_resumen_creado ON resumen (creado_en);

-- Los envíos automáticos, uno por período: para no repetirlos ni salteárselos aunque la PC haya estado apagada.
--   ENVIADO:  se mandó (resumen_id apunta al resumen).
--   OMITIDO:  la primera vez que corre la aplicación, el período vencido no se manda (no se manda historia).
--   OFRECIDO: había varios pendientes; se mandó el más reciente y este quedó en "Ver anteriores".
CREATE TABLE resumen_envio (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo        VARCHAR(20) NOT NULL,
    desde       DATE        NOT NULL,
    hasta       DATE        NOT NULL,
    estado      VARCHAR(20) NOT NULL,
    resumen_id  BIGINT REFERENCES resumen (id),
    actualizado TIMESTAMP   NOT NULL,
    CONSTRAINT uq_resumen_envio UNIQUE (tipo, desde),
    CONSTRAINT ck_resumen_envio_tipo CHECK (tipo IN ('SEMANAL', 'MENSUAL')),
    CONSTRAINT ck_resumen_envio_estado CHECK (estado IN ('ENVIADO', 'OMITIDO', 'OFRECIDO')),
    CONSTRAINT ck_resumen_envio_enviado CHECK (estado <> 'ENVIADO' OR resumen_id IS NOT NULL)
);

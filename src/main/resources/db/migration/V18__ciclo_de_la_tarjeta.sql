-- Ciclo de la tarjeta de crédito: un resumen por mes, con su cierre y su vencimiento. Las compras con crédito y las
-- cuotas no se guardan acá: cada una pertenece al resumen cuyo período la incluye, y eso se calcula en Java.
CREATE TABLE resumen_tarjeta (
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tarjeta_id               BIGINT         NOT NULL REFERENCES tarjeta (id),
    -- El mes del cierre (día 1), sin correrlo por fin de semana: hay un resumen por tarjeta y por mes.
    periodo                  DATE           NOT NULL,
    cierre                   DATE           NOT NULL,
    vencimiento              DATE           NOT NULL,
    -- FALSE: las fechas son una estimación de Java (≈) hasta que el usuario las carga.
    fechas_confirmadas       BOOLEAN        NOT NULL DEFAULT FALSE,
    -- Lo que dice el resumen del banco, si el usuario lo cargó (puede no coincidir con lo cargado en Gastito).
    total_real               NUMERIC(14, 2),
    estado                   VARCHAR(20)    NOT NULL,
    -- El PAGO_TARJETA con el que se debitó (no cuenta como gasto).
    pago_movimiento_id       BIGINT         REFERENCES movimiento (id) ON DELETE SET NULL,
    -- Recordatorios: cuándo se preguntó por las fechas, hasta cuándo se pospuso ("Todavía no"), cuándo se avisó
    -- del vencimiento y cuándo se preguntó si se debitó.
    pregunta_fechas_en       DATE,
    fechas_pospuestas_hasta  DATE,
    aviso_vencimiento_en     DATE,
    pregunta_debito_en       DATE,
    creado_en                TIMESTAMP      NOT NULL,
    CONSTRAINT uq_resumen_tarjeta_periodo UNIQUE (tarjeta_id, periodo),
    CONSTRAINT ck_resumen_tarjeta_fechas CHECK (vencimiento > cierre),
    CONSTRAINT ck_resumen_tarjeta_estado CHECK (estado IN ('ABIERTO', 'CERRADO', 'PAGADO')),
    CONSTRAINT ck_resumen_tarjeta_total CHECK (total_real IS NULL OR total_real >= 0)
);

CREATE INDEX ix_movimiento_tarjeta_fecha ON movimiento (tarjeta_id, fecha_hora);

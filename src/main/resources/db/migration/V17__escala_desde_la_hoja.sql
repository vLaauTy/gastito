-- Los nombres de fila de la hoja que reconoce cada concepto (se editan en el dashboard). La clave es el nombre sin
-- mayúsculas, acentos, espacios ni puntos ("A.I.S." = "ais"). Dos filas no son concepto: la hora normal (el valor
-- de la hora de la escala) y "Valores netos" (un control). Las filas que no tienen alias se ignoran.
CREATE TABLE alias_escala (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alias       VARCHAR(100) NOT NULL,
    clave       VARCHAR(100) NOT NULL UNIQUE,
    destino     VARCHAR(20)  NOT NULL,
    concepto_id BIGINT REFERENCES concepto_sueldo (id),
    CONSTRAINT ck_alias_escala_destino CHECK (
        (destino = 'CONCEPTO' AND concepto_id IS NOT NULL)
        OR (destino IN ('HORA_NORMAL', 'VALORES_NETOS') AND concepto_id IS NULL))
);


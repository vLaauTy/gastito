-- Compras en dólares con la tarjeta de crédito. monto sigue siendo en pesos (lo que suman todos los totales): hasta
-- que llega el resumen es una estimación con la cotización de referencia (monto_estimado), o 0 si no había ninguna.
ALTER TABLE movimiento ADD COLUMN monto_original NUMERIC(14, 2);
-- Pesos por dólar: la de referencia al estimar, o la real (monto ÷ monto_original) al corregir con el resumen.
ALTER TABLE movimiento ADD COLUMN cotizacion_usada NUMERIC(14, 4);

ALTER TABLE movimiento DROP CONSTRAINT ck_movimiento_monto;
ALTER TABLE movimiento ADD CONSTRAINT ck_movimiento_monto
    -- Una compra en dólares sin cotización queda con 0 pesos ("≈ sin estimar") hasta que se corrige.
    CHECK ((monto IS NOT NULL AND (monto > 0 OR (monto = 0 AND moneda = 'USD')))
        OR (monto IS NULL AND estado <> 'CONFIRMADO'));
ALTER TABLE movimiento ADD CONSTRAINT ck_movimiento_moneda CHECK (moneda IN ('ARS', 'USD'));
ALTER TABLE movimiento ADD CONSTRAINT ck_movimiento_dolares
    CHECK (moneda = 'ARS' OR (monto_original IS NOT NULL AND monto_original > 0));

-- La cotización de referencia del dólar tarjeta que carga el usuario (/dolar 1500): vale la última.
CREATE TABLE cotizacion_dolar (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    valor      NUMERIC(14, 2) NOT NULL,
    cargada_en TIMESTAMP      NOT NULL,
    CONSTRAINT ck_cotizacion_dolar_valor CHECK (valor > 0)
);

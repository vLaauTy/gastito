-- Etapa 3: fotos de tickets. El detalle por producto y dónde quedó la foto.
-- Tiene que correr igual en H2 (modo PostgreSQL) y en PostgreSQL.

-- Lo que dice el ticket, aparte de la descripción (que el usuario puede editar). Sirve para reconocer compras
-- repetidas en el mismo comercio.
ALTER TABLE movimiento ADD COLUMN comercio VARCHAR(100);

-- Ruta relativa de la foto (tickets/AAAA/MM/<id>.jpg, adentro de la carpeta de datos). Solo en los tickets.
ALTER TABLE movimiento ADD COLUMN foto_ticket VARCHAR(255);
ALTER TABLE movimiento ADD CONSTRAINT ck_movimiento_foto_ticket
    CHECK (foto_ticket IS NULL OR origen = 'TICKET');

-- Un renglón del ticket, en el orden impreso. Los descuentos van como renglones con subtotal negativo.
-- No se guarda nada más del ticket (ni tarjeta, ni CUIT, ni cajero).
CREATE TABLE movimiento_item (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    movimiento_id   BIGINT         NOT NULL REFERENCES movimiento (id) ON DELETE CASCADE,
    orden           INTEGER        NOT NULL,
    descripcion     VARCHAR(255)   NOT NULL,
    cantidad        NUMERIC(10, 3),
    precio_unitario NUMERIC(14, 2),
    subtotal        NUMERIC(14, 2) NOT NULL,
    CONSTRAINT uq_movimiento_item_orden UNIQUE (movimiento_id, orden),
    CONSTRAINT ck_movimiento_item_cantidad CHECK (cantidad IS NULL OR cantidad > 0)
);

-- Etapa 6: compras repetidas, juntadas, gastos fijos, cuotas y movimientos entre cuentas.

-- Juntadas: el movimiento guarda mi parte (lo que cuenta como gasto); acá va el total que pagué y desde dónde, que
-- es lo que se compara con un aviso o con el resumen de la tarjeta.
CREATE TABLE juntada (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    movimiento_id  BIGINT         NOT NULL REFERENCES movimiento (id) ON DELETE CASCADE,
    total_pagado   NUMERIC(14, 2) NOT NULL,
    personas       INTEGER        NOT NULL,
    medio_pago_id  BIGINT REFERENCES medio_pago (id),
    cuenta_id      BIGINT REFERENCES cuenta (id),
    tarjeta_id     BIGINT REFERENCES tarjeta (id),
    creado_en      TIMESTAMP      NOT NULL,
    CONSTRAINT uq_juntada_movimiento UNIQUE (movimiento_id),
    CONSTRAINT ck_juntada_total CHECK (total_pagado > 0),
    CONSTRAINT ck_juntada_personas CHECK (personas >= 2)
);

-- Los demás (yo no): cuánto me debe cada uno y si ya me pagó.
CREATE TABLE juntada_participante (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    juntada_id        BIGINT         NOT NULL REFERENCES juntada (id) ON DELETE CASCADE,
    orden             INTEGER        NOT NULL,
    nombre            VARCHAR(60)    NOT NULL,
    monto             NUMERIC(14, 2) NOT NULL,
    estado            VARCHAR(20)    NOT NULL,
    pagado_en         TIMESTAMP,
    -- La DEVOLUCION con la que pagó, o el gasto en que se convirtió su parte si se dio por perdida.
    devolucion_id     BIGINT REFERENCES movimiento (id),
    gasto_perdido_id  BIGINT REFERENCES movimiento (id),
    CONSTRAINT ck_participante_monto CHECK (monto >= 0),
    CONSTRAINT ck_participante_estado CHECK (estado IN ('PENDIENTE', 'PAGADO', 'PERDIDO'))
);

CREATE INDEX ix_participante_juntada ON juntada_participante (juntada_id);

-- Gastos fijos: lo que se cobra todos los meses (o cada dos), con el monto que se espera.
CREATE TABLE gasto_fijo (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre          VARCHAR(80)    NOT NULL,
    monto_esperado  NUMERIC(14, 2) NOT NULL,
    categoria_id    BIGINT         NOT NULL REFERENCES categoria (id),
    medio_pago_id   BIGINT REFERENCES medio_pago (id),
    cuenta_id       BIGINT REFERENCES cuenta (id),
    tarjeta_id      BIGINT REFERENCES tarjeta (id),
    -- Si el mes no tiene ese día (un 31), se cobra el último.
    dia_del_mes     INTEGER        NOT NULL,
    frecuencia      VARCHAR(10)    NOT NULL,
    -- El primer mes que se cobra: los bimestrales van cada dos meses desde acá.
    mes_inicio      DATE           NOT NULL,
    monto_variable  BOOLEAN        NOT NULL DEFAULT FALSE,
    activo          BOOLEAN        NOT NULL DEFAULT TRUE,
    creado_en       TIMESTAMP      NOT NULL,
    CONSTRAINT ck_gasto_fijo_monto CHECK (monto_esperado > 0),
    CONSTRAINT ck_gasto_fijo_dia CHECK (dia_del_mes BETWEEN 1 AND 31),
    CONSTRAINT ck_gasto_fijo_frecuencia CHECK (frecuencia IN ('MENSUAL', 'BIMESTRAL'))
);

-- Compras en cuotas: cada cuota es un movimiento con plan_cuotas_id, cuota_actual y cuota_total.
CREATE TABLE plan_cuotas (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descripcion   VARCHAR(255),
    total         NUMERIC(14, 2) NOT NULL,
    cantidad      INTEGER        NOT NULL,
    valor_cuota   NUMERIC(14, 2) NOT NULL,
    fecha_compra  TIMESTAMP      NOT NULL,
    -- El mes de la primera cuota (el de la compra o el siguiente, según gastito.cuotas.primera-cuota).
    primer_mes    DATE           NOT NULL,
    categoria_id  BIGINT REFERENCES categoria (id),
    tarjeta_id    BIGINT REFERENCES tarjeta (id),
    estado        VARCHAR(20)    NOT NULL,
    creado_en     TIMESTAMP      NOT NULL,
    CONSTRAINT ck_plan_cuotas_total CHECK (total > 0 AND valor_cuota > 0),
    CONSTRAINT ck_plan_cuotas_cantidad CHECK (cantidad >= 2),
    CONSTRAINT ck_plan_cuotas_estado CHECK (estado IN ('ACTIVO', 'CANCELADO'))
);

-- AUTOMATICO: lo genera Gastito (el cobro de un fijo, las cuotas de una compra).
ALTER TABLE movimiento DROP CONSTRAINT ck_movimiento_origen;
ALTER TABLE movimiento ADD CONSTRAINT ck_movimiento_origen
    CHECK (origen IN ('TEXTO', 'AUDIO', 'TICKET', 'AVISO', 'RESUMEN', 'DASHBOARD', 'AUTOMATICO'));

ALTER TABLE movimiento ADD COLUMN gasto_fijo_id BIGINT REFERENCES gasto_fijo (id);
-- El mes (día 1) al que corresponde el cobro de un fijo: hay uno por fijo y por mes, aunque se cancele ("este mes no").
ALTER TABLE movimiento ADD COLUMN fijo_periodo DATE;
ALTER TABLE movimiento ADD COLUMN plan_cuotas_id BIGINT REFERENCES plan_cuotas (id);
-- Solo en ENTRE_CUENTAS: cuenta_id es el origen y esta, el destino.
ALTER TABLE movimiento ADD COLUMN cuenta_destino_id BIGINT REFERENCES cuenta (id);

ALTER TABLE movimiento ADD CONSTRAINT ck_movimiento_fijo
    CHECK ((gasto_fijo_id IS NULL AND fijo_periodo IS NULL) OR (gasto_fijo_id IS NOT NULL AND fijo_periodo IS NOT NULL));
ALTER TABLE movimiento ADD CONSTRAINT ck_movimiento_cuenta_destino
    CHECK (cuenta_destino_id IS NULL OR tipo = 'ENTRE_CUENTAS');

CREATE INDEX ix_movimiento_gasto_fijo ON movimiento (gasto_fijo_id, fijo_periodo);
CREATE INDEX ix_movimiento_plan_cuotas ON movimiento (plan_cuotas_id);

-- Compras repetidas: cuando dos movimientos se unen, queda uno y acá se anota lo que aportó el otro.
CREATE TABLE movimiento_union (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    movimiento_id   BIGINT         NOT NULL REFERENCES movimiento (id) ON DELETE CASCADE,
    origen          VARCHAR(20)    NOT NULL,
    monto           NUMERIC(14, 2),
    fecha_hora      TIMESTAMP,
    texto_original  VARCHAR(1000),
    creado_en       TIMESTAMP      NOT NULL
);

CREATE INDEX ix_movimiento_union_movimiento ON movimiento_union (movimiento_id);

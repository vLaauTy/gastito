-- Etapa 8 (sueldo): calculadora de sueldo y recibo como control.

-- Los conceptos del sueldo. Cambian con el convenio: se editan desde el dashboard, no están en el código.
-- Las horas llevan su factor como fracción (3/2, 2/1, 8/60) para que la cuenta dé exacta.
CREATE TABLE concepto_sueldo (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre      VARCHAR(100) NOT NULL,
    tipo        VARCHAR(25)  NOT NULL,
    factor_num  INT,
    factor_den  INT,
    orden       INT          NOT NULL,
    activo      BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT ck_concepto_sueldo_tipo CHECK (tipo IN
        ('REMUNERATIVO_FIJO', 'HORAS', 'NO_REMUNERATIVO', 'DESCUENTO_PORCENTAJE')),
    CONSTRAINT ck_concepto_sueldo_factor CHECK (
        (tipo = 'HORAS' AND factor_num > 0 AND factor_den > 0) OR (tipo <> 'HORAS' AND factor_num IS NULL
        AND factor_den IS NULL))
);

-- Una escala: los valores que rigen desde una fecha (paritarias). Las anteriores se conservan.
CREATE TABLE escala_sueldo (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vigente_desde  DATE           NOT NULL UNIQUE,
    valor_hora     NUMERIC(14, 2) NOT NULL
);

-- El monto fijo (o el porcentaje, en los descuentos) de cada concepto en una escala.
CREATE TABLE escala_valor (
    escala_id   BIGINT         NOT NULL REFERENCES escala_sueldo (id) ON DELETE CASCADE,
    concepto_id BIGINT         NOT NULL REFERENCES concepto_sueldo (id),
    valor       NUMERIC(14, 4) NOT NULL,
    PRIMARY KEY (escala_id, concepto_id)
);

-- El cálculo de un mes trabajado. Las líneas guardan lo que dio cada concepto: si después cambian la escala o los
-- conceptos, el historial no se mueve.
CREATE TABLE calculo_sueldo (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Siempre el día 1 del mes trabajado.
    periodo          DATE           NOT NULL UNIQUE,
    escala_id        BIGINT         NOT NULL REFERENCES escala_sueldo (id),
    valor_hora       NUMERIC(14, 2) NOT NULL,
    bruto            NUMERIC(14, 2) NOT NULL,
    descuentos       NUMERIC(14, 2) NOT NULL,
    neto_haberes     NUMERIC(14, 2) NOT NULL,
    no_remunerativo  NUMERIC(14, 2) NOT NULL,
    neto_total       NUMERIC(14, 2) NOT NULL,
    calculado_en     TIMESTAMP      NOT NULL
);

CREATE TABLE calculo_sueldo_linea (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    calculo_id  BIGINT         NOT NULL REFERENCES calculo_sueldo (id) ON DELETE CASCADE,
    concepto_id BIGINT         NOT NULL REFERENCES concepto_sueldo (id),
    nombre      VARCHAR(100)   NOT NULL,
    tipo        VARCHAR(25)    NOT NULL,
    -- Las horas cargadas (solo en los conceptos por horas).
    cantidad    NUMERIC(10, 2),
    -- El monto fijo o el porcentaje de la escala (vacío en las horas).
    valor       NUMERIC(14, 4),
    importe     NUMERIC(14, 2) NOT NULL,
    -- Si el importe se pisó a mano para ese mes.
    ajustado    BOOLEAN        NOT NULL DEFAULT FALSE,
    orden       INT            NOT NULL
);

CREATE INDEX ix_calculo_linea_calculo ON calculo_sueldo_linea (calculo_id, orden);

-- El recibo ya no crea el ingreso: es un control. Se vincula al sueldo cobrado de su período, que puede cargarse
-- después (o no estar vinculado todavía).
ALTER TABLE recibo_sueldo ALTER COLUMN movimiento_id DROP NOT NULL;

-- A qué concepto del sueldo corresponde cada renglón del recibo (vacío: "otro").
ALTER TABLE recibo_concepto ADD COLUMN concepto_sueldo_id BIGINT REFERENCES concepto_sueldo (id);

-- Lo que la IA mapeó una vez se reutiliza con los recibos siguientes. La clave es la descripción normalizada.
CREATE TABLE mapeo_concepto_recibo (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clave              VARCHAR(150) NOT NULL UNIQUE,
    concepto_sueldo_id BIGINT REFERENCES concepto_sueldo (id)
);


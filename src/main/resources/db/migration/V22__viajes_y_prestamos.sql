-- Viajes y préstamos a personas. Nada de esto cambia los movimientos que ya existen: las columnas nuevas de
-- movimiento empiezan vacías.

-- Un viaje (Bariloche): una etiqueta para los movimientos. La fecha de cada gasto sigue siendo la real.
CREATE TABLE viaje (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre           VARCHAR(100)   NOT NULL,
    emoji            VARCHAR(16),
    desde            DATE           NOT NULL,
    hasta            DATE           NOT NULL,
    -- Cuántos van, contándome (opcional: sirve para el "por persona" del resumen final).
    personas         INTEGER,
    -- Opcional: sin presupuesto, solo se muestran los totales.
    presupuesto      NUMERIC(14, 2),
    notas            VARCHAR(1000),
    -- Los avisos del modo viaje: el primer día, el último y el resumen final (una sola vez cada uno).
    aviso_inicio_en  TIMESTAMP,
    aviso_fin_en     TIMESTAMP,
    resumen_final_en TIMESTAMP,
    creado_en        TIMESTAMP      NOT NULL,
    CONSTRAINT ck_viaje_fechas CHECK (hasta >= desde),
    CONSTRAINT ck_viaje_personas CHECK (personas IS NULL OR personas >= 1),
    CONSTRAINT ck_viaje_presupuesto CHECK (presupuesto IS NULL OR presupuesto > 0)
);

-- Lo que falta pagar del viaje (hospedaje, traslados…), con un monto aproximado opcional. Al pagarlo se crea el gasto
-- y queda anotado acá.
CREATE TABLE viaje_pendiente (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    viaje_id         BIGINT         NOT NULL REFERENCES viaje (id) ON DELETE CASCADE,
    descripcion      VARCHAR(255)   NOT NULL,
    monto_aproximado NUMERIC(14, 2),
    categoria_id     BIGINT REFERENCES categoria (id),
    movimiento_id    BIGINT REFERENCES movimiento (id),
    pagado_en        TIMESTAMP,
    creado_en        TIMESTAMP      NOT NULL,
    CONSTRAINT ck_viaje_pendiente_monto CHECK (monto_aproximado IS NULL OR monto_aproximado > 0)
);
CREATE INDEX ix_viaje_pendiente_viaje ON viaje_pendiente (viaje_id);

-- Cualquier movimiento puede ser de un viaje.
ALTER TABLE movimiento ADD COLUMN viaje_id BIGINT REFERENCES viaje (id);
CREATE INDEX ix_movimiento_viaje ON movimiento (viaje_id);

-- Plata que le presté a alguien y me devuelve en cuotas. No es gasto mío: queda "a cobrar", como la parte de los
-- demás en una juntada. Si salió del mismo pago que un gasto mío (pagué los vuelos de los dos), movimiento_id es ese
-- gasto, y el préstamo vale solo mientras el gasto esté guardado.
CREATE TABLE prestamo (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    persona        VARCHAR(60)    NOT NULL,
    descripcion    VARCHAR(255),
    monto          NUMERIC(14, 2) NOT NULL,
    cuotas         INTEGER        NOT NULL,
    valor_cuota    NUMERIC(14, 2) NOT NULL,
    -- El mes de la primera cuota (día 1) y el día aproximado en que me paga cada una.
    primer_mes     DATE           NOT NULL,
    dia            INTEGER        NOT NULL,
    fecha          DATE           NOT NULL,
    cuenta_id      BIGINT REFERENCES cuenta (id),
    medio_pago_id  BIGINT REFERENCES medio_pago (id),
    movimiento_id  BIGINT REFERENCES movimiento (id),
    viaje_id       BIGINT REFERENCES viaje (id),
    -- PENDIENTE: falta confirmarlo (uno cargado solo); ACTIVO: me debe; TERMINADO: ya me pagó todo.
    estado         VARCHAR(20)    NOT NULL,
    texto_original VARCHAR(1000),
    creado_en      TIMESTAMP      NOT NULL,
    CONSTRAINT ck_prestamo_monto CHECK (monto > 0),
    CONSTRAINT ck_prestamo_cuotas CHECK (cuotas >= 1),
    CONSTRAINT ck_prestamo_valor_cuota CHECK (valor_cuota > 0),
    CONSTRAINT ck_prestamo_dia CHECK (dia BETWEEN 1 AND 31),
    CONSTRAINT ck_prestamo_estado CHECK (estado IN ('PENDIENTE', 'ACTIVO', 'TERMINADO'))
);
CREATE INDEX ix_prestamo_movimiento ON prestamo (movimiento_id);

-- Cada cuota: su mes, cuándo vence, cuánto y si ya me la pagó. Si paga de más o de menos, las que siguen se acomodan.
CREATE TABLE prestamo_cuota (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prestamo_id     BIGINT         NOT NULL REFERENCES prestamo (id) ON DELETE CASCADE,
    numero          INTEGER        NOT NULL,
    vence           DATE           NOT NULL,
    monto           NUMERIC(14, 2) NOT NULL,
    estado          VARCHAR(20)    NOT NULL,
    cobrada_en      TIMESTAMP,
    -- La DEVOLUCION con la que se cobró (un pago puede cubrir más de una cuota).
    devolucion_id   BIGINT REFERENCES movimiento (id),
    -- El aviso de cuota atrasada se manda una sola vez.
    aviso_enviado_en TIMESTAMP,
    CONSTRAINT uq_prestamo_cuota UNIQUE (prestamo_id, numero),
    CONSTRAINT ck_prestamo_cuota_monto CHECK (monto >= 0),
    CONSTRAINT ck_prestamo_cuota_estado CHECK (estado IN ('PENDIENTE', 'COBRADA', 'ATRASADA'))
);

-- Etapa 6 (extra): checklist mensual de gastos fijos.

-- Alias para reconocer el fijo en un mensaje ("edesur", "luz"), separados por coma.
ALTER TABLE gasto_fijo ADD COLUMN alias VARCHAR(255);
-- Si el bot sigue proponiendo el monto esperado (el flujo automático de siempre) o espera que el usuario
-- cargue el gasto y lo vincule por nombre/alias (el checklist mensual).
ALTER TABLE gasto_fijo ADD COLUMN proponer_monto BOOLEAN NOT NULL DEFAULT TRUE;

-- Cuándo se mandó el último recordatorio agrupado de fijos atrasados (una sola fila).
CREATE TABLE recordatorio_fijo (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    enviado_en  TIMESTAMP NOT NULL
);

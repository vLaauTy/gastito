-- Esquema inicial de Gastito.
-- Tiene que correr igual en H2 (modo PostgreSQL) y en PostgreSQL.
-- Las fechas se guardan como TIMESTAMP sin zona, en hora de America/Argentina/Buenos_Aires.

CREATE TABLE categoria (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre         VARCHAR(100) NOT NULL UNIQUE,
    -- Palabras sueltas (sin tildes, separadas por coma) que reconoce el parser simple.
    palabras_clave VARCHAR(500),
    activa         BOOLEAN      NOT NULL DEFAULT TRUE
);

CREATE TABLE medio_pago (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre         VARCHAR(50)  NOT NULL UNIQUE,
    palabras_clave VARCHAR(500),
    activo         BOOLEAN      NOT NULL DEFAULT TRUE
);

CREATE TABLE cuenta (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre         VARCHAR(50)  NOT NULL UNIQUE,
    palabras_clave VARCHAR(500),
    activa         BOOLEAN      NOT NULL DEFAULT TRUE
);

CREATE TABLE tarjeta (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre           VARCHAR(100) NOT NULL UNIQUE,
    banco            VARCHAR(50),
    -- Cuenta desde la que se debita el pago del resumen.
    cuenta_debito_id BIGINT REFERENCES cuenta (id),
    activa           BOOLEAN      NOT NULL DEFAULT TRUE
);

-- Diccionario para reconocer nombres raros del resumen de la tarjeta (se usa desde la etapa 7).
CREATE TABLE alias_comercio (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patron          VARCHAR(100) NOT NULL UNIQUE,
    nombre_comercio VARCHAR(100) NOT NULL,
    categoria_id    BIGINT       NOT NULL REFERENCES categoria (id),
    gasto_fijo      BOOLEAN      NOT NULL DEFAULT FALSE
);

CREATE TABLE movimiento (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_hora     TIMESTAMP     NOT NULL,
    monto          NUMERIC(14, 2) NOT NULL,
    moneda         VARCHAR(3)    NOT NULL DEFAULT 'ARS',
    descripcion    VARCHAR(255),
    tipo           VARCHAR(20)   NOT NULL,
    categoria_id   BIGINT REFERENCES categoria (id),
    medio_pago_id  BIGINT REFERENCES medio_pago (id),
    cuenta_id      BIGINT REFERENCES cuenta (id),
    tarjeta_id     BIGINT REFERENCES tarjeta (id),
    juntada        BOOLEAN       NOT NULL DEFAULT FALSE,
    -- Compras en cuotas (etapa 7): cuota_actual de cuota_total.
    cuota_actual   INTEGER,
    cuota_total    INTEGER,
    origen         VARCHAR(20)   NOT NULL,
    estado         VARCHAR(20)   NOT NULL,
    texto_original VARCHAR(1000),
    creado_en      TIMESTAMP     NOT NULL,
    CONSTRAINT ck_movimiento_monto CHECK (monto > 0),
    CONSTRAINT ck_movimiento_tipo CHECK (tipo IN ('GASTO', 'INGRESO', 'DEVOLUCION', 'PAGO_TARJETA', 'ENTRE_CUENTAS')),
    CONSTRAINT ck_movimiento_origen CHECK (origen IN ('TEXTO', 'AUDIO', 'TICKET', 'AVISO', 'RESUMEN')),
    CONSTRAINT ck_movimiento_estado CHECK (estado IN ('PENDIENTE', 'CONFIRMADO', 'CANCELADO')),
    CONSTRAINT ck_movimiento_cuotas CHECK (
        (cuota_actual IS NULL AND cuota_total IS NULL)
        OR (cuota_actual >= 1 AND cuota_total >= 1 AND cuota_actual <= cuota_total))
);

CREATE INDEX ix_movimiento_estado_fecha ON movimiento (estado, fecha_hora);
CREATE INDEX ix_movimiento_categoria ON movimiento (categoria_id);

CREATE TABLE uso_ia (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_hora     TIMESTAMP      NOT NULL,
    modelo         VARCHAR(50)    NOT NULL,
    tokens_entrada BIGINT         NOT NULL,
    tokens_salida  BIGINT         NOT NULL,
    proposito      VARCHAR(20)    NOT NULL,
    costo_usd      NUMERIC(12, 6) NOT NULL,
    movimiento_id  BIGINT REFERENCES movimiento (id),
    CONSTRAINT ck_uso_ia_proposito CHECK (proposito IN ('TEXTO', 'AUDIO', 'TICKET', 'RESUMEN', 'CONSULTA'))
);

CREATE INDEX ix_uso_ia_fecha ON uso_ia (fecha_hora);


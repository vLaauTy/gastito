-- Ahorros invertidos (Cocos, CEDEARs, un FCI…): no son ingresos ni gastos. Una cuenta de inversión tiene una "bolsa"
-- (la plata sin detalle, o sin invertir) y, si se quiere, posiciones con nombre libre. Lo que se puso sale del saldo
-- inicial, de los aportes y retiros (ENTRE_CUENTAS en movimiento) y de las compras y ventas internas; lo que vale, de
-- las valuaciones que se cargan a mano.

-- Las cuentas que ya existen son bancarias (o billeteras): las de inversión no se usan para pagar gastos.
ALTER TABLE cuenta ADD COLUMN tipo VARCHAR(20) DEFAULT 'BANCARIA' NOT NULL;
ALTER TABLE cuenta ADD CONSTRAINT ck_cuenta_tipo CHECK (tipo IN ('BANCARIA', 'INVERSION'));
-- Solo en una de inversión: cada cuántos días se pregunta cuánto vale (null: no se pregunta) y cuándo se preguntó.
ALTER TABLE cuenta ADD COLUMN recordatorio_dias INTEGER;
ALTER TABLE cuenta ADD COLUMN recordatorio_enviado_en TIMESTAMP;
ALTER TABLE cuenta ADD CONSTRAINT ck_cuenta_recordatorio
    CHECK (recordatorio_dias IS NULL OR (tipo = 'INVERSION' AND recordatorio_dias > 0));

-- Una posición dentro de una cuenta de inversión ("CEDEAR SPY", "FCI money market").
CREATE TABLE posicion_inversion (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cuenta_id      BIGINT       NOT NULL REFERENCES cuenta (id),
    nombre         VARCHAR(100) NOT NULL,
    -- Las palabras con las que se la nombra ("spy"), sin tildes y separadas por coma.
    palabras_clave VARCHAR(500),
    activa         BOOLEAN      DEFAULT TRUE NOT NULL,
    creada_en      TIMESTAMP    NOT NULL,
    CONSTRAINT uq_posicion_inversion UNIQUE (cuenta_id, nombre)
);

-- Lo que se puso que no es un movimiento: el saldo inicial (ahorro previo, de la bolsa si posicion_id es null) y las
-- compras y ventas dentro de la cuenta (de la bolsa a una posición y al revés). No cuentan como ingreso ni gasto.
CREATE TABLE operacion_inversion (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cuenta_id      BIGINT         NOT NULL REFERENCES cuenta (id),
    posicion_id    BIGINT REFERENCES posicion_inversion (id),
    tipo           VARCHAR(20)    NOT NULL,
    monto          NUMERIC(14, 2) NOT NULL,
    fecha          DATE           NOT NULL,
    texto_original VARCHAR(1000),
    creada_en      TIMESTAMP      NOT NULL,
    CONSTRAINT ck_operacion_inversion_tipo CHECK (tipo IN ('SALDO_INICIAL', 'COMPRA', 'VENTA')),
    CONSTRAINT ck_operacion_inversion_monto CHECK (monto > 0),
    CONSTRAINT ck_operacion_inversion_posicion CHECK (tipo = 'SALDO_INICIAL' OR posicion_id IS NOT NULL)
);

-- Cuánto valía la bolsa (posicion_id null) o una posición en una fecha. MANUAL: lo dijo el usuario; IGUAL: "Igual que
-- antes"; AJUSTE: lo movió un aporte, un retiro o una compra (el valor anterior más o menos lo que se movió). El
-- historial no se recalcula.
CREATE TABLE valuacion_inversion (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cuenta_id   BIGINT         NOT NULL REFERENCES cuenta (id),
    posicion_id BIGINT REFERENCES posicion_inversion (id),
    fecha       DATE           NOT NULL,
    valor       NUMERIC(14, 2) NOT NULL,
    origen      VARCHAR(20)    NOT NULL,
    -- Solo en un AJUSTE: lo que lo movió (si se borra, se borra el ajuste).
    movimiento_id BIGINT REFERENCES movimiento (id),
    operacion_id  BIGINT REFERENCES operacion_inversion (id),
    creada_en   TIMESTAMP      NOT NULL,
    CONSTRAINT ck_valuacion_inversion_valor CHECK (valor >= 0),
    CONSTRAINT ck_valuacion_inversion_origen CHECK (origen IN ('MANUAL', 'IGUAL', 'AJUSTE')),
    CONSTRAINT ck_valuacion_inversion_ajuste
        CHECK (origen = 'AJUSTE' OR (movimiento_id IS NULL AND operacion_id IS NULL))
);
CREATE INDEX ix_valuacion_inversion_cuenta ON valuacion_inversion (cuenta_id, fecha);

-- Parte del valor de una cuenta apartada para una meta ("300.000 de Cocos para Bariloche"). Liberada: ya no cuenta.
CREATE TABLE reserva_inversion (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cuenta_id   BIGINT         NOT NULL REFERENCES cuenta (id),
    meta        VARCHAR(100)   NOT NULL,
    monto       NUMERIC(14, 2) NOT NULL,
    creada_en   TIMESTAMP      NOT NULL,
    liberada_en TIMESTAMP,
    CONSTRAINT ck_reserva_inversion_monto CHECK (monto > 0)
);

package ar.gastito.catalogo;

/** Qué es una cuenta: dónde está la plata del día a día o dónde están los ahorros invertidos. */
public enum TipoCuenta {
    /** Un banco o una billetera (Galicia, Mercado Pago): con ella se pagan gastos y se cobran ingresos. */
    BANCARIA,
    /** Ahorros invertidos (Cocos): no es un medio de pago; su valor cambia y se actualiza a mano. */
    INVERSION
}
